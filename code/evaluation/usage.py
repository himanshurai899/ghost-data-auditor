"""Render code/evaluation/usage_report.md from a run's usage.jsonl + manifest and the page-cache build ledger.

    python code/evaluation/usage.py --run <run_id|latest> [--out code/evaluation/usage_report.md]
"""
import argparse
import json
import sys
from pathlib import Path

CODE = Path(__file__).resolve().parents[1]
REPO = CODE.parent
PRICING = CODE / "config" / "pricing.json"
LEDGER = CODE / "data" / "usage_cache_build.jsonl"


def _jsonl(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _n(v):
    return "n/a" if v is None else f"{v:,}"


def _cost(rates, inp, out):
    """USD estimate, or None when any rate or token count needed is unknown (never invented)."""
    if not rates or rates.get("input") is None or rates.get("output") is None or inp is None or out is None:
        return None
    return (inp * rates["input"] + out * rates["output"]) / 1e6


def table(rows: list[dict], pricing: dict) -> tuple[list[str], dict]:
    """Per-model rows plus an overall row. Token sums are None when any call in the group lacks the count."""
    groups: dict = {}
    for r in rows:
        groups.setdefault((r.get("provider", "nvidia"), r["model"], r["role"]), []).append(r)

    def agg(rs, rates=None):
        s = lambda k: None if any(r.get(k) is None for r in rs) else sum(r[k] for r in rs)
        inp, out = s("prompt_tokens"), s("output_tokens")
        tot = s("total_tokens") if any("total_tokens" in r for r in rs) else (None if inp is None or out is None else inp + out)
        return {"calls": len(rs), "cached": sum(1 for r in rs if r.get("cached")), "in": inp, "out": out, "tot": tot,
                "cost": _cost(rates, inp, out)}

    lines = ["| Provider | Model | Role | Calls | Cached | Input tokens | Output tokens | Total tokens | Est. cost (USD) |",
             "|---|---|---|---|---|---|---|---|---|"]
    costs = []
    for (prov, mdl, role), rs in sorted(groups.items()):
        a = agg(rs, pricing["models"].get(mdl))
        costs.append(a["cost"])
        lines.append(f"| {prov} | {mdl} | {role} | {a['calls']} | {a['cached']} | {_n(a['in'])} | {_n(a['out'])} | {_n(a['tot'])} | "
                     f"{'not estimated' if a['cost'] is None else format(a['cost'], '.4f')} |")
    total = agg(rows)
    total["cost"] = None if not rows else (None if None in costs else sum(costs))
    if not rows:
        lines.append("| none | none | none | 0 | 0 | 0 | 0 | 0 | 0.0000 |")
        total["cost"] = 0.0
    lines.append(f"| **Overall** | | | **{total['calls']}** | **{total['cached']}** | **{_n(total['in'])}** | **{_n(total['out'])}** | "
                 f"**{_n(total['tot'])}** | **{'not estimated' if total['cost'] is None else format(total['cost'], '.4f')}** |")
    return lines, total


def render(run_dir: Path) -> str:
    pricing = json.loads(PRICING.read_text(encoding="utf-8"))
    manifest = json.loads((run_dir / "manifest.json").read_text(encoding="utf-8"))
    usage = _jsonl(run_dir / "usage.jsonl")
    build = _jsonl(LEDGER)
    reqs = manifest.get("cases") or 0
    rt_lines, rt = table(usage, pricing)
    cb_lines, cb = table(build, pricing)
    per_tok = "n/a" if not reqs or rt["tot"] is None else f"{rt['tot'] / reqs:,.1f}"
    per_cost = "not estimated" if not reqs or rt["cost"] is None else f"${rt['cost'] / reqs:.6f}"
    mode = "offline (cache-only, fails closed on a miss)" if manifest.get("offline") else "online (live fallbacks allowed)"
    src = pricing.get("source") or "none (no public per-token price list recorded)"
    return "\n".join([
        "# Usage Report", "",
        "> Generated by `code/evaluation/usage.py` from `runs/<run_id>/usage.jsonl`, the run manifest and "
        "`code/data/usage_cache_build.jsonl`. Do not edit by hand.", "",
        "## 1. Final full-dataset run (the run that produced `output.csv`)", "",
        f"- Run `{manifest['run_id']}` at git `{manifest.get('git_sha', 'unknown')}`, mode: {mode}.",
        f"- Requests: {reqs} · model calls: {rt['calls']} ({rt['cached']} served from cache, {rt['calls'] - rt['cached']} live) · "
        f"total tokens: {_n(rt['tot'])}",
        f"- Average tokens per request: {per_tok} · estimated cost per request: {per_cost}",
        "- Every decision in this run is deterministic code over the cached evidence facts; an offline run makes zero model calls "
        "unless a cached `--online` fallback is replayed.", "",
        *rt_lines, "",
        "## 2. One-time page-cache build (`python code/ghost/ev_page.py --refresh`)", "",
        "Rendered screenshot pages were read once with Nemotron Parse and the extracted facts committed under `code/data/pages/`; "
        "the run above reads those facts, not the model. This cost is outside the per-request numbers.", "",
        f"- Calls: {cb['calls']} · total tokens: {_n(cb['tot'])}",
        "- Input tokens are not reported by the Parse endpoint, and the raw responses of the original 11 calls were not retained, "
        "so their token counts are recorded as null (shown n/a), not estimated. Future `--refresh` runs record output tokens.", "",
        *cb_lines, "",
        "## 3. Cost basis", "",
        "- Billed cost: $0. All calls went to the NVIDIA build free tier.",
        f"- Estimates use reference rates in `code/config/pricing.json`; source: {src}. A null rate or unknown token count prints "
        "`not estimated`.", ""])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="latest")
    ap.add_argument("--out", default=str(CODE / "evaluation" / "usage_report.md"))
    a = ap.parse_args()
    runs = REPO / "runs"
    if a.run == "latest":
        cands = sorted(d for d in runs.glob("*") if (d / "usage.jsonl").is_file() and (d / "manifest.json").is_file())
        if not cands:
            sys.exit("no run with usage.jsonl under runs/; run python code/main.py first")
        run_dir = cands[-1]
    else:
        run_dir = runs / a.run
    Path(a.out).write_text(render(run_dir), encoding="utf-8", newline="\n")
    print(f"wrote {a.out} from {run_dir.name}")


if __name__ == "__main__":
    main()
